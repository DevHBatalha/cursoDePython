palavra = input('Escreva qualquer coisa: ')
print('-' * 47)
print('O tipo primitive desse valor é: ', type(palavra))
print('É um número: ', palavra.isalnum())
print('Só tem espaço: ', palavra.isspace())
print('É alfabetico: ', palavra.isalpha())
print('É alfanumerico: ', palavra.isalnum())
print('-' * 28)
print('Está ém maiúsculas: ', palavra.isupper())
print('Está em minúsculas: ', palavra.islower())
print('Está em capitalizada: ', palavra.istitle())