#A tupla é uma variável composta e imutável, ou seja os seus dados não pode ser alterado.

#              0           1       2        3
lanche = ("Hamburguer", "Suco", "Pizza", "Pudim")
print(lanche)
print(lanche[2])
print(lanche[1:3])
print(lanche[:2])
print(lanche[1:])
print(lanche[-1])
print(len(lanche)) # este comando montra o tamanho da tupla